#!/usr/bin/env python3
"""Evaluate one generated population against the ground truth of the same people.

Individual level: exact activity-sequence match, LCS F1, and location
(administrative dong), dwell and trip mode on LCS-matched activities.
Environment level: feasibility rate, reward component means, realized leg modes.
Distribution level: Jensen-Shannon divergences for the whole population and
within persona subgroups (tripchain/population_metrics.py).

The decisions scored are the final ones in each rollout's decision_trace, so
decisions regenerated by refinement are the ones evaluated. Writes
<output-dir>/metrics.json, subgroup_metrics.csv and two overview figures.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tripchain.population_metrics import age_bucket, jsd, population_metrics  # noqa: E402
from tripchain.rewards import lcs_pairs  # noqa: E402
from tripchain.trip_modes import mode_preference_from_trips  # noqa: E402


def read(path: str) -> list[dict]:
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line]


def by_id(rows: list[dict]) -> dict[str, dict]:
    return {str(row["person_id"]): row for row in rows}


def location_key(location: dict) -> tuple[str, str, str]:
    return (
        str(location.get("scope") or location.get("sido") or "").casefold(),
        str(location.get("gu") or location.get("sigungu") or "").casefold(),
        str(location.get("administrative_dong_name") or "").casefold(),
    )


DWELL_BIN_MIN, DWELL_BINS = 60, 12  # hours, last bin = 12h or more
TRAVEL_BIN_MIN, TRAVEL_BINS = 10, 12  # 10-minute bins, last = 2h or more


def binned(minutes: float, width: int, last: int) -> int:
    return min(max(int(minutes // width), 0), last)


def timing_values(activities: list[dict], travel_times: list[float]) -> dict[str, list]:
    """Binned timing of one day: dwell per non-home activity (excluding the last
    activity, whose dwell is the rest of the day), first departure hour and
    travel time per trip. activities: [(activity_type, start_min, dwell_min)]."""
    if len(activities) < 2:
        return {}
    return {
        "dwell_time": [
            f"{kind}|{binned(dwell, DWELL_BIN_MIN, DWELL_BINS)}" for kind, _, dwell in activities[:-1] if kind != "home"
        ],
        "first_departure_hour": [binned(activities[0][1] + activities[0][2], 60, 23)],
        "travel_time": [binned(t, TRAVEL_BIN_MIN, TRAVEL_BINS) for t in travel_times if t >= 0],
    }


def truth_timing(target: dict) -> dict[str, list]:
    acts = [
        (a["activity_type"], float(a["start_time_min"]), float(a["dwell_time_min"]))
        for a in target.get("activities") or []
    ]
    travel = [acts[i + 1][1] - (acts[i][1] + acts[i][2]) for i in range(len(acts) - 1)]
    return timing_values(acts, travel)


def realized_timing(rollout: dict) -> dict[str, list]:
    """Timing after the environment scheduled the day (final trip chain)."""
    environment = (rollout.get("decision_trace") or {}).get("environment") or {}
    chain = environment.get("final_trip_chain") or {}
    acts = [
        (a["activity_type"], float(a["start_min"]), float(a["end_min"]) - float(a["start_min"]))
        for a in chain.get("activities") or []
    ]
    return timing_values(acts, [float(t["travel_time_min"]) for t in chain.get("trips") or []])


STUDENT1_KEYS = ("persona_bundle", "reasoning1", "activity_sequence")
STUDENT2_KEYS = ("reasoning2", "location_dwell_by_activity", "trip_modes")


def overlay_rollout_decisions(s1: dict[str, dict], s2: dict[str, dict], rollouts: dict[str, dict]) -> int:
    """Replace Student1/2 outputs with the final ones in each rollout's decision_trace
    (in place; demographics and other input fields stay). Returns how many people changed."""
    changed = 0
    for pid, rollout in rollouts.items():
        trace = rollout.get("decision_trace") or {}
        before = (
            s1.get(pid, {}).get("activity_sequence"),
            s2.get(pid, {}).get("location_dwell_by_activity"),
            s2.get(pid, {}).get("trip_modes"),
        )
        for store, name, keys in ((s1, "student1", STUDENT1_KEYS), (s2, "student2", STUDENT2_KEYS)):
            output = (trace.get(name) or {}).get("output")
            if pid in store and isinstance(output, dict):
                store[pid] = {**store[pid], **{k: output[k] for k in keys if k in output}}
        after = (
            s1.get(pid, {}).get("activity_sequence"),
            s2.get(pid, {}).get("location_dwell_by_activity"),
            s2.get(pid, {}).get("trip_modes"),
        )
        changed += before != after
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ground-truth", required=True)
    parser.add_argument("--student1", required=True)
    parser.add_argument("--student2", required=True)
    parser.add_argument("--rollouts", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--limit", type=int, default=0, help="first N people of --ground-truth (0: everyone)")
    args = parser.parse_args()
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)

    truth_all = read(args.ground_truth)
    if args.limit:
        truth_all = truth_all[: args.limit]
    ordered_ids = [str(row["person_id"]) for row in truth_all]
    truth, s1, s2, rollouts = map(by_id, [truth_all, read(args.student1), read(args.student2), read(args.rollouts)])
    # Refinement (Lv2/Lv3) regenerates Student1/2 decisions inside the rollout, so the
    # decisions actually executed are the ones in each rollout's decision_trace.
    decisions_replaced = overlay_rollout_decisions(s1, s2, rollouts)
    shared = [pid for pid in ordered_ids if pid in s1 and pid in s2]
    grounded = [pid for pid in shared if pid in rollouts]

    exact = []
    lcs_scores = []
    location_hits = []
    dwell_errors = []
    mode_hits = []
    trip_mode_hits = []
    pred_trip_modes, true_trip_modes = Counter(), Counter()
    pred_lengths, true_lengths = [], []
    subgroup: dict[tuple[str, str], list[dict]] = defaultdict(list)
    distribution_people = []
    for pid in shared:
        p1, p2, target = s1[pid], s2[pid], truth[pid]
        pseq, tseq = p1["activity_sequence"], target["activity_sequence"]
        pairs = lcs_pairs(pseq, tseq)
        exact.append(pseq == tseq)
        lcs_scores.append(2 * len(pairs) / max(1, len(pseq) + len(tseq)))
        pred_lengths.append(len(pseq))
        true_lengths.append(len(tseq))
        for pi, ti in pairs:
            if pi >= len(p2["location_dwell_by_activity"]) or ti >= len(target["activities"]):
                continue
            pred_item = p2["location_dwell_by_activity"][pi]
            true_item = target["activities"][ti]
            location_hits.append(location_key(pred_item["location"]) == location_key(true_item["location"]))
            dwell_errors.append(abs(float(pred_item["dwell_time_min"]) - float(true_item["dwell_time_min"])))
        # Per-trip main modes (when Student2 names them): trip i arrives at activity i+1.
        if "trip_modes" in p2 and "trip_modes" in target:
            pred_trip_modes.update(p2["trip_modes"])
            true_trip_modes.update(target["trip_modes"])
            trip_mode_hits.extend(
                p2["trip_modes"][pi - 1] == target["trip_modes"][ti - 1]
                for pi, ti in pairs
                if 0 < pi <= len(p2["trip_modes"]) and 0 < ti <= len(target["trip_modes"])
            )
        pmode = mode_preference_from_trips(p2["trip_modes"]) if "trip_modes" in p2 else p2.get("mode_preference") or []
        tmode = target.get("mode_preference") or []
        if pmode and tmode:
            mode_hits.append(pmode[0]["mode"] == tmode[0]["mode"])
        demo = p1.get("demographics") or {}
        truth_extra, pred_extra = {}, {}
        if "trip_modes" in p2 and "trip_modes" in target:
            truth_extra["trip_mode"], pred_extra["trip_mode"] = target["trip_modes"], p2["trip_modes"]
        # Timing is compared only where both sides have it (realized days need a rollout).
        realized = realized_timing(rollouts[pid]) if pid in rollouts else {}
        if realized:
            truth_times = truth_timing(target)
            for name in set(truth_times) | set(realized):
                truth_extra[name], pred_extra[name] = truth_times.get(name, []), realized.get(name, [])
        distribution_people.append(
            {
                "demographics": demo,
                "truth": tseq,
                "pred": pseq,
                "truth_mode": tmode[0]["mode"] if tmode else None,
                "pred_mode": pmode[0]["mode"] if pmode else None,
                "truth_extra": truth_extra,
                "pred_extra": pred_extra,
            }
        )
        record = {"exact": float(pseq == tseq), "lcs": lcs_scores[-1]}
        subgroup[("gender", str(demo.get("gender", "unknown")))].append(record)
        subgroup[("age", age_bucket(demo.get("age", 0)))].append(record)

    environment_rows = [
        row["decision_trace"]["environment"]
        for pid in grounded
        if isinstance((row := rollouts[pid]).get("decision_trace"), dict)
        and isinstance(row["decision_trace"].get("environment"), dict)
    ]
    reward_rows = [rollouts[pid]["rewards"] for pid in grounded if rollouts[pid].get("rewards")]
    statuses = Counter(rollouts[pid].get("status", "unknown") for pid in grounded)
    components = sorted({key for row in reward_rows for key in row["components"]})
    component_means = {
        key: float(np.mean([row["components"].get(key, 0.0) for row in reward_rows])) for key in components
    }
    selected_trips = [trip for env in environment_rows for trip in (env.get("final_trip_chain") or {}).get("trips", [])]
    selected_modes = Counter(trip.get("mode", "unknown") for trip in selected_trips)
    share = lambda counts: {k: round(v / max(1, sum(counts.values())), 4) for k, v in counts.most_common()}
    metrics = {
        "requested_people": args.limit or len(truth_all),
        "student1_success_people": len(s1),
        "student2_success_people": len(s2),
        "shared_prediction_people": len(shared),
        "environment_completed_people": len(grounded),
        "decision_source": "rollout_decision_trace",
        "people_with_refined_decisions": decisions_replaced,
        "activity_sequence_exact_accuracy": float(np.mean(exact)) if exact else None,
        "activity_sequence_lcs_f1_mean": float(np.mean(lcs_scores)) if lcs_scores else None,
        "location_dong_exact_on_lcs": float(np.mean(location_hits)) if location_hits else None,
        "dwell_median_absolute_error_min": float(np.median(dwell_errors)) if dwell_errors else None,
        "dwell_within_30_min": float(np.mean(np.asarray(dwell_errors) <= 30)) if dwell_errors else None,
        "mode_preference_top1_accuracy": float(np.mean(mode_hits)) if mode_hits else None,
        "trip_mode_accuracy_on_lcs": float(np.mean(trip_mode_hits)) if trip_mode_hits else None,
        "trip_mode_share_predicted": share(pred_trip_modes) if pred_trip_modes else None,
        "trip_mode_share_truth": share(true_trip_modes) if true_trip_modes else None,
        "trip_mode_share_jsd": jsd(pred_trip_modes, true_trip_modes) if pred_trip_modes else None,
        # Legs realized in another mode because Student2's could not be routed.
        "mode_fallback_legs": sum(bool(trip.get("mode_fallback")) for trip in selected_trips),
        "feasible_rate": statuses.get("ok", 0) / max(1, len(grounded)),
        # Activities outside Seoul cannot be grounded, so those people are not judged.
        "outside_poi_coverage_people": statuses.get("outside_poi_coverage", 0),
        "feasible_rate_within_poi_coverage": statuses.get("ok", 0)
        / max(1, len(grounded) - statuses.get("outside_poi_coverage", 0)),
        "initial_plan_feasible_rate": float(
            np.mean([bool(row.get("initial_plan_feasible")) for row in environment_rows])
        )
        if environment_rows
        else None,
        "mean_weighted_reward": float(np.mean([row["weighted_total"] for row in reward_rows])) if reward_rows else None,
        "reward_component_means": component_means,
        "status_counts": dict(statuses),
        "selected_leg_mode_counts": dict(selected_modes),
        "selected_leg_mode_share": share(selected_modes),
        # Distribution level (JSD vs ground truth, lower is better): whole population and
        # within persona subgroups. See tripchain/population_metrics.py.
        "distribution": population_metrics(distribution_people),
    }
    (output / "metrics.json").write_text(json.dumps(metrics, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    with (output / "subgroup_metrics.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["dimension", "group", "people", "activity_exact", "activity_lcs_f1"])
        for (dimension, group), values in sorted(subgroup.items()):
            writer.writerow(
                [
                    dimension,
                    group,
                    len(values),
                    np.mean([row["exact"] for row in values]),
                    np.mean([row["lcs"] for row in values]),
                ]
            )

    labels = [
        "Activity\nexact",
        "Activity\nLCS-F1",
        "Location\ndong",
        "Dwell\n±30m",
        "Mode pref.\nTop-1",
        "Network\nfeasible",
    ]
    values = [
        metrics["activity_sequence_exact_accuracy"],
        metrics["activity_sequence_lcs_f1_mean"],
        metrics["location_dong_exact_on_lcs"],
        metrics["dwell_within_30_min"],
        metrics["mode_preference_top1_accuracy"],
        metrics["feasible_rate"],
    ]
    figure, axis = plt.subplots(figsize=(12, 6.5))
    bars = axis.bar(
        labels,
        [100 * (value or 0) for value in values],
        color=["#4C78A8", "#72B7B2", "#F58518", "#E45756", "#B279A2", "#54A24B"],
    )
    axis.set_ylim(0, 100)
    axis.set_ylabel("Percent")
    axis.set_title(f"TripChain performance — same held-out population (n={len(shared):,})")
    axis.grid(axis="y", alpha=0.25)
    axis.set_axisbelow(True)
    for bar, value in zip(bars, values):
        axis.text(
            bar.get_x() + bar.get_width() / 2,
            100 * (value or 0) + 2,
            f"{100 * (value or 0):.1f}",
            ha="center",
            fontweight="bold",
        )
    figure.tight_layout()
    figure.savefig(output / "performance_dashboard.png", dpi=180)
    plt.close(figure)

    figure, axes = plt.subplots(2, 2, figsize=(13, 9))
    bins = np.arange(1, max(pred_lengths + true_lengths + [2]) + 2) - 0.5
    axes[0, 0].hist(true_lengths, bins=bins, alpha=0.65, label="GT")
    axes[0, 0].hist(pred_lengths, bins=bins, alpha=0.65, label="Student1")
    axes[0, 0].set_title("Activity-chain length")
    axes[0, 0].legend()
    axes[0, 1].hist(np.clip(dwell_errors, 0, 600), bins=40, color="#E45756", alpha=0.8)
    axes[0, 1].set_title("Dwell absolute error (clipped at 600 min)")
    if component_means:
        axes[1, 0].bar(list(component_means), list(component_means.values()), color="#4C78A8")
        axes[1, 0].tick_params(axis="x", rotation=35)
        axes[1, 0].set_title("Mean dense-reward components")
    if selected_modes:
        axes[1, 1].bar(list(selected_modes), list(selected_modes.values()), color="#54A24B")
        axes[1, 1].tick_params(axis="x", rotation=35)
        axes[1, 1].set_title("Selected leg modes")
    figure.tight_layout()
    figure.savefig(output / "diagnostic_distributions.png", dpi=180)
    plt.close(figure)
    print(json.dumps(metrics, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
